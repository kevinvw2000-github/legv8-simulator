// Example programs for the Examples menu. Each one is original teaching code that opens ready to
// step through, with its starting values, watches and (where it helps) expected results. Tests
// run every example and check that it does what its description says.

import type { WatchSpec } from './watch';
import type { Mode } from './state';

export type ExampleGroup = 'Basics' | 'Numbers and bits' | 'Memory' | 'Procedures' | 'Debugging' | 'Full LEGv8';
export const EXAMPLE_GROUPS: readonly ExampleGroup[] = [
  'Basics',
  'Numbers and bits',
  'Memory',
  'Procedures',
  'Debugging',
  'Full LEGv8',
];

export interface Example {
  id: string;
  group: ExampleGroup;
  title: string;
  /** One or two sentences: what it shows and what to try. */
  description: string;
  code: string;
  mode: Mode;
  /** Starting values, as typed in the Registers and Memory panels (decimal). */
  registers: Array<{ key: string; value: string }>;
  memory: Array<{ key: string; value: string }>;
  watches: WatchSpec[];
  /** Expected-results fields (zyBooks pair format). */
  expected: { registers: string; memory: string };
  /** 1-based source lines that start with a breakpoint. */
  breakpoints?: number[];
  /**
   * What running it does, so tests can check it:
   * ok = finishes with every expected value matching; wrong-result = finishes but misses the expected
   * value (a bug to find); loops = never finishes (a bug to find); error = stops with an error.
   */
  outcome: 'ok' | 'wrong-result' | 'loops' | 'error';
}

const lines = (...l: string[]): string => l.join('\n');
const reg = (key: string, value: string) => ({ key, value });
const none = { registers: '', memory: '' };

